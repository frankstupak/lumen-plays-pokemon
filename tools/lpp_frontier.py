def map_label(mid):
    """ROM name when known, else the raw id -- a fact, never a guess (wq#503)."""
    if mid is None:
        return "?"
    n = MAP_NAMES.get(mid)
    return n if n else f"map{mid}"

# ---------------------------------------------------------------- evidence
def _iso(ms):
    return datetime.fromtimestamp(ms / 1000, timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")


def _parse_iso(s):
    return datetime.fromisoformat(s.replace("Z", "+00:00")).timestamp() * 1000


def load_sidecars(base=BASE):
    """Checkpoint sidecars: exact-ts evidence that outlives the run that wrote it.

    wq#862: sidecars whose (map, x, y) the claimed map cannot physically hold
    are excluded. These are torn reads — the position was sampled mid-warp,
    inheriting coordinates from the map being LEFT under the id of the map being
    ENTERED. resume.readProgress() rejects them via coordsPlausible() (wq#699);
    this is the Python-side equivalent so the frontier never ranks or displays
    an impossible tuple.
    """
    out = []
    rejected = 0
    for p in glob.glob(f"{base}/checkpoints/**/*.json", recursive=True):
        try:
            j = json.load(open(p))
        except Exception:
            continue
        if not isinstance(j, dict) or "ts" not in j or "map" not in j:
            continue
        m, x, y = j.get("map"), j.get("x"), j.get("y")
        if isinstance(m, int) and isinstance(x, int) and isinstance(y, int):
            if not coords_plausible(m, x, y):
                rejected += 1
                continue
        out.append(j)
    if rejected:
        print(f"  [wq#862] {rejected} sidecar(s) rejected by plausibility check", file=sys.stderr)
    return out


def load_runs(base=BASE):
    out = []
    for p in sorted(glob.glob(f"{base}/events/run-summary-*.json")):
        try:
            out.append(json.load(open(p)))
        except Exception:
            continue
    out.sort(key=lambda j: j.get("startedAt", ""))
    return out


def evidence(base=BASE):
    """Merged, time-sorted evidence points: (ts_ms, map, badges, events, source).

    Run-summary map sightings are stamped at the run's END, the latest instant
    the sighting could have occurred. Understating an advance's age is the safe
    direction for a stall detector: it can only ever delay an alert, never
    manufacture one.
    """
    ev = []
    for j in load_sidecars(base):
        ev.append((j["ts"], j.get("map"), j.get("badges") or 0,
                   j.get("events") or 0, "sidecar"))
    for j in load_runs(base):
        st = j.get("startedAt")
        if not st:
            continue
        try:
            t = _parse_iso(st) + (j.get("wallMs") or 0)
        except Exception:
            continue
        b = j.get("badges") or 0
        for m in (j.get("mapsSeen") or []):
            ev.append((t, m, b, None, "runsum"))
    ev.sort(key=lambda r: r[0])
    return ev

# ---------------------------------------------------------------- frontier walk
RULES = ("strict", "events", "newmap")


def advances(ev, rule="strict"):
    """Walk evidence forward, returning every moment the frontier ADVANCED.

    rule="strict"  badges + critical-path depth only            (what we ship)
    rule="events"  strict + raw event-flag count                (backtest foil)
    rule="newmap"  strict + any never-before-seen map id        (backtest foil,
                   this is the rule the ticket suggested; it fails on history)
    """
    maxb, maxe, maxr = -1, -1, -1
    seen = set()
    out = []
    for ts, m, b, e, src in ev:
        why = []
        if b > maxb:
            if maxb >= 0:                      # first sighting is a baseline
                why.append(f"badges {maxb}->{b}")
            maxb = b
        r = RANK.get(m)
        if r is not None and r > maxr:
            if maxr >= 0:
                why.append(f"reached {map_label(m)} (path {r}/{LAST_RANK})")
            maxr = r
        if rule == "events" and e is not None and e > maxe:
            if maxe >= 0:
                why.append(f"eventFlags {maxe}->{e}")
            maxe = e
        elif e is not None and e > maxe:
            maxe = e
        if rule == "newmap" and m is not None and m not in seen and seen:
            why.append(f"new map {map_label(m)}")
        if m is not None:
            seen.add(m)
        if why:
            out.append({"ts": ts, "why": ", ".join(why), "src": src,
                        "badges": maxb, "rank": maxr, "events": maxe})
    return out


def _live_progress():
    """storyScore/objective from the running service. Context only; never resets."""
    try:
        with urllib.request.urlopen(PROGRESS_URL, timeout=3) as r:
            return json.load(r)
    except Exception:
        return None

# ---------------------------------------------------------------- state
def _cost_since(runs, since_ms, until_ms=None):
    """Turns / wall hours / tokens burned by runs that STARTED after an instant.

    This is what makes the alert land: "frozen 102h" is a number, "frozen 102h
    and 4,318 turns and 18.6M tokens" is a decision.
    """
    turns = tokens = 0
    hours = 0.0
    n = 0
    for j in runs:
        st = j.get("startedAt")
        if not st:
            continue
        try:
            t = _parse_iso(st)
        except Exception:
            continue
        if t < since_ms or (until_ms is not None and t > until_ms):
            continue
        n += 1
        turns += j.get("turns") or 0
        hours += (j.get("wallMs") or 0) / 3.6e6
        tokens += ((j.get("derived") or {}).get("tokensTotal")) or 0
    return {"runs": n, "turns": turns, "hours": hours, "tokens": tokens}


def compute(base=BASE, window_h=DEFAULT_WINDOW_H, now_ms=None, rule="strict",
            live=True):
    ev = evidence(base)
    if not ev:
        return {"ok": False, "reason": "no evidence on disk (no sidecars, no run summaries)"}
    now_ms = now_ms if now_ms is not None else datetime.now(timezone.utc).timestamp() * 1000
    # "The frontier AS OF now_ms." Evidence stamped later than the instant being
    # asked about is excluded, so the function can replay any past moment --
    # which is what makes the backtest and the probe's synthetic histories mean
    # anything. Live callers pass no now_ms, so nothing is filtered for them.
    ev = [e for e in ev if e[0] <= now_ms]
    if not ev:
        return {"ok": False, "reason": f"no evidence at or before {_iso(now_ms)}"}
    runs = load_runs(base)
    adv = advances(ev, rule)
    last = adv[-1] if adv else None
    last_ts = last["ts"] if last else ev[0][0]
    frozen_h = (now_ms - last_ts) / 3.6e6

    maxb = max((e[2] or 0) for e in ev)
    maxe = max((e[3] or 0) for e in ev if e[3] is not None) if any(e[3] is not None for e in ev) else None
    ranks = [RANK[e[1]] for e in ev if e[1] in RANK]
    maxr = max(ranks) if ranks else -1
    maps_ever = sorted({e[1] for e in ev if e[1] is not None})

    # Loop shape: the traversal, newest last. Sidecars ONLY -- one map per
    # sidecar with an exact ts, so their order is a real sequence. Run summaries
    # cannot be used here: they stamp every map in mapsSeen at the same instant
    # (the run's end), so map order inside a run is list order, not visit order,
    # and rendering that as a path would be a confident lie about the route.
    # Consecutive repeats collapse, which is what makes an A->B->A->B
    # oscillation visible instead of drowning in duplicates.
    side = sorted((j["ts"], j.get("map")) for j in load_sidecars(base)
                  if j.get("map") is not None and j["ts"] <= now_ms)
    recent = []
    for _, m in side:
        if not recent or recent[-1] != m:
            recent.append(m)
    recent = recent[-8:]

    st = {
        "ok": True,
        "generatedAt": _iso(now_ms),
        "rule": rule,
        "windowHours": window_h,
        "maxBadges": maxb,
        "maxEventFlags": maxe,
        "furthestMap": CRITICAL_PATH[maxr][0] if maxr >= 0 else None,
        "furthestLabel": CRITICAL_PATH[maxr][1] if maxr >= 0 else "(off critical path)",
        "furthestRank": maxr,
        "lastRank": LAST_RANK,
        "nextMilestone": CRITICAL_PATH[maxr + 1][1] if 0 <= maxr < LAST_RANK else None,
        "pathExhausted": maxr >= LAST_RANK,
        "mapsEverCount": len(maps_ever),
        "mapsEver": maps_ever,
        "recentMaps": [{"id": m, "label": map_label(m)} for m in recent],
        "lastAdvanceAt": _iso(last_ts),
        "lastAdvanceWhy": last["why"] if last else "(baseline: no advance recorded yet)",
        "frozenHours": frozen_h,
        "stalled": frozen_h > window_h,
        "cost": _cost_since(runs, last_ts, now_ms),
        "advanceCount": len(adv),
    }
    if live:
        p = _live_progress()
        if p:
            st["storyScore"] = p.get("storyScore")
            st["storyMax"] = p.get("storyMax")
            st["objective"] = p.get("objective")
    return st

# ---------------------------------------------------------------- persistence
def persist(st, path=STATE):
    """Merge-max cache of the high-water mark.

    The frontier is always RECOMPUTED from evidence, so this file is a record,
    not a source of truth -- but merging with max() means archiving or pruning
    old checkpoints can never make the recorded frontier go backwards.
    """
    try:
        prev = json.load(open(path))
    except Exception:
        prev = {}
    merged = dict(st)
    for k in ("maxBadges", "furthestRank", "maxEventFlags", "mapsEverCount"):
        a, b = prev.get(k), st.get(k)
        if isinstance(a, int) and isinstance(b, int):
            merged[k] = max(a, b)
    if prev.get("furthestRank", -1) > st.get("furthestRank", -1):
        merged["furthestLabel"] = prev.get("furthestLabel")
        merged["furthestMap"] = prev.get("furthestMap")
    merged["firstSeenAt"] = prev.get("firstSeenAt") or st.get("generatedAt")
    try:
        os.makedirs(os.path.dirname(path), exist_ok=True)
        tmp = path + ".tmp"
        json.dump(merged, open(tmp, "w"), indent=1)
        os.replace(tmp, path)
    except Exception:
        pass
    return merged


# ---------------------------------------------------------------- alert text
def format_alert(st):
    """(key, message). Actionable per ticket item 3: names the frozen value, how
    long, what is next, what it has cost, and the loop shape."""
    if st.get("pathExhausted"):
        return ("frontier_path_end",
                f"FRONTIER: the agent reached the last mapped milestone "
                f"({st['furthestLabel']}). Extend CRITICAL_PATH in "
                f"tools/lpp_frontier.py or this check goes blind from here.")
    c = st.get("cost") or {}
    shape = " -> ".join(m["label"] for m in st.get("recentMaps", [])) or "?"
    nxt = st.get("nextMilestone") or "?"
    story = (f", storyScore {st['storyScore']}/{st.get('storyMax','?')}"
             if st.get("storyScore") is not None else "")
    return ("frontier_stall",
            f"FRONTIER FROZEN {st['frozenHours']:.1f}h (window {st['windowHours']:.0f}h): "
            f"badges {st['maxBadges']}, furthest {st['furthestLabel']} "
            f"(path {st['furthestRank']}/{st['lastRank']}), NEXT = {nxt}{story}. "
            f"Burned since: {c.get('runs',0)} runs, {c.get('turns',0)} turns, "
            f"{c.get('hours',0):.0f}h, {c.get('tokens',0)/1e6:.1f}M tokens. "
            f"Last advance {st['lastAdvanceAt']} ({st['lastAdvanceWhy']}). "
            f"Recent maps: {shape}")


# ---------------------------------------------------------------- backtest
def gaps_for(ev, rule):
    """(closed_gaps, trailing_gap) in hours.

    A CLOSED gap is a quiet stretch that ended in a real advance: the agent was
    slow but it was getting somewhere, so an alert there is a FALSE POSITIVE.
    The TRAILING gap is the quiet stretch still running at the end of evidence:
    that is the stall we must catch. The threshold has to separate the two.
    """
    adv = advances(ev, rule)
    end = ev[-1][0]
    closed = []
    for i in range(1, len(adv)):
        closed.append(((adv[i]["ts"] - adv[i - 1]["ts"]) / 3.6e6,
                       adv[i - 1], adv[i]))
    trailing = ((end - adv[-1]["ts"]) / 3.6e6, adv[-1], end) if adv else None
    return adv, closed, trailing


def backtest(base=BASE, thresholds=(4, 6, 8, 10, 12, 16, 24)):
    ev = evidence(base)
    print(f"EVIDENCE: {len(ev)} points, {_iso(ev[0][0])} .. {_iso(ev[-1][0])} "
          f"({len(load_sidecars(base))} sidecars, {len(load_runs(base))} run summaries)\n")
    for rule in RULES:
        adv, closed, trailing = gaps_for(ev, rule)
        print(f"===== rule={rule}: {len(adv)} frontier advances =====")
        for a in adv:
            print(f"   {_iso(a['ts'])}  [{a['src']:<7}]  {a['why']}")
        closed_sorted = sorted(closed, key=lambda g: -g[0])
        print(f"   longest SLOW-BUT-PROGRESSING stretch (must NOT alert): "
              f"{closed_sorted[0][0]:.2f}h" if closed_sorted else "   (no closed gaps)")
        if closed_sorted:
            for g, a, b in closed_sorted[:3]:
                print(f"      {g:7.2f}h  {_iso(a['ts'])} -> {_iso(b['ts'])}  ends: {b['why']}")
        if trailing:
            print(f"   TRAILING stall (must alert): {trailing[0]:.2f}h since "
                  f"{_iso(trailing[1]['ts'])} ({trailing[1]['why']})")
        print(f"   {'window':>8} {'false alerts':>13} {'catches stall':>14}  first fire")
        for T in thresholds:
            fp = [g for g in closed if g[0] > T]
            catch = bool(trailing and trailing[0] > T)
            fire = _iso(trailing[1]["ts"] + T * 3.6e6) if catch else "-"
            print(f"   {T:>6}h {len(fp):>13} {('YES' if catch else 'no'):>14}  {fire}")
        print()
    return 0


# ---------------------------------------------------------------- restart loop
# wq#515 ABSORBED SCOPE (was wq#504 MISS 2).
#
# The frontier above answers "has the game moved forward?". This answers the
# question that explains WHY it has not: the harness keeps booting the same
# save. One boot on a checkpoint is a resume; nine boots on one checkpoint is a
# loop, and it is the signal that would have caught the wq#518 resume trap on
# 2026-08-08 instead of five days later.
#
# Evidence is the run summary's resumedFrom filename. The map id embedded in
# that name was VERIFIED against the checkpoint sidecar's RAM-read map for
# every checkpoint on disk (33/33 exact, 0 mismatches) before this parse was
# trusted. probe_frontier re-runs that comparison, so if the naming convention
# ever changes the probe fails instead of this check quietly lying.
RESUME_MAP_RE = re.compile(r"-map(\d+)\.")


_SIDECAR_MAPS = {}


def _sidecar_map_index(base=BASE):
    """stem -> RAM-read map id, for resolving a resumed checkpoint's map.

    WHY THIS EXISTS (found live 2026-08-13T06:58Z, the moment wq#518 landed):
    the filename parse alone is not enough. Only 46 of 192 checkpoints are
    `-map<N>` named; 139 are `-t<N>` named and carry NO map id in the filename.
    The freeze happened on map15-named saves, so the parse looked sufficient --
    and then the resume fix started selecting t-named saves and the rewind half
    of this check went blind on 72% of the checkpoint set, exactly when it was
    needed to confirm the fix holds.

    The sidecar's `map` is a RAM read, so this is also the stronger source:
    in this project a filename is a hypothesis and RAM is evidence.
    """
    if base in _SIDECAR_MAPS:
        return _SIDECAR_MAPS[base]
    idx = {}
    for p in glob.glob(f"{base}/checkpoints/**/*.json", recursive=True):
        try:
            j = json.load(open(p))
        except Exception:
            continue
        m = j.get("map")
        if not isinstance(m, int):
            continue
        # wq#862: exclude torn-read sidecars from the map index too.
        x, y = j.get("x"), j.get("y")
        if isinstance(x, int) and isinstance(y, int) and not coords_plausible(m, x, y):
            continue
        idx[os.path.basename(p)[:-5]] = m
    _SIDECAR_MAPS[base] = idx
    return idx


def resume_map(resumed_from, base=BASE):
    """Map id a boot resumed onto: sidecar RAM read first, filename as fallback."""
    if not resumed_from:
        return None
    stem = os.path.basename(resumed_from)
    for suffix in (".state.gz", ".gz", ".state"):
        if stem.endswith(suffix):
            stem = stem[: -len(suffix)]
            break
    m = _sidecar_map_index(base).get(stem)
    if isinstance(m, int):
        return m
    mm = RESUME_MAP_RE.search(resumed_from)
    return int(mm.group(1)) if mm else None


def load_boots(base=BASE, now_ms=None):
    """One record per boot, oldest first: when, from which save, how deep it got."""
    out = []
    for j in load_runs(base):
        st = j.get("startedAt")
        if not st:
            continue
        try:
            t = _parse_iso(st)
        except Exception:
            continue
        if now_ms is not None and t > now_ms:
            continue
        src = j.get("resumedFrom")
        rmap = resume_map(src, base)
        ranks = [RANK[x] for x in (j.get("mapsSeen") or []) if x in RANK]
        out.append({
            "startedAt": st, "ts": t, "resumedFrom": src,
            "resumeMap": rmap, "resumeRank": RANK.get(rmap) if rmap is not None else None,
            "resumeLabel": map_label(rmap) if rmap is not None else "?",
            "deepestRank": max(ranks) if ranks else None,
            "turns": j.get("turns") or 0,
        })
    out.sort(key=lambda r: r["ts"])
    return out


def restart_loop(base=BASE, now_ms=None, min_streak=2, boots=None):
    """Two independent cross-run pathologies, reported together.

    repeat  the same resumedFrom across >= min_streak consecutive boots. The
            harness is not advancing its own starting point.
    rewind  a boot that resumes SHALLOWER on the critical path than the run
            before it actually reached. That is progress being discarded, and
            it is the rewind stated directly rather than inferred from flatness.

    Deliberately NOT keyed on the frontier: a rewind is visible on the very
    next boot, hours before any 12h stall window can close.
    """
    bs = boots if boots is not None else load_boots(base, now_ms)
    if not bs:
        return {"ok": False, "reason": "no run summaries on disk"}

    streak, streak_from = 1, bs[-1].get("resumedFrom")
    if streak_from:
        for prev in reversed(bs[:-1]):
            if prev.get("resumedFrom") == streak_from:
                streak += 1
            else:
                break
    else:
        streak = 0

    rewinds = []
    for prev, cur in zip(bs, bs[1:]):
        pr, cr = prev.get("deepestRank"), cur.get("resumeRank")
        if pr is None or cr is None or cr >= pr:
            continue
        rewinds.append({
            "at": cur["startedAt"], "resumedFrom": cur.get("resumedFrom"),
            "resumeLabel": cur["resumeLabel"], "resumeRank": cr,
            "lostFromRank": pr, "lostFromLabel": CRITICAL_PATH[pr][1],
            "turnsDiscarded": prev.get("turns") or 0,
        })

    # Only the CURRENT streak alarms. Historical repeats are context: a fixed
    # trap must be allowed to fall out of the alert without rewriting history.
    # Turns discarded BY this streak: every boot in it except the one still
    # running had its run thrown away by the next same-save boot. Counted from
    # the streak's own boots, not from the rewind list, because the two are not
    # index-aligned and pretending they are is how a number becomes a guess.
    streak_boots = bs[-streak:] if streak else []
    discarded = sum(b.get("turns") or 0 for b in streak_boots[:-1])
    deepest = max(rewinds, key=lambda r: r["lostFromRank"]) if rewinds else None

    return {
        "ok": True, "boots": len(bs), "streak": streak, "streakSave": streak_from,
        "minStreak": min_streak, "rewinds": rewinds,
        "rewindsRecent": [r for r in rewinds[-5:]],
        "turnsDiscardedInStreak": discarded, "deepestRewind": deepest,
        "lastBootAt": bs[-1]["startedAt"], "lastResumeLabel": bs[-1]["resumeLabel"],
        "looping": bool(streak_from) and streak >= min_streak,
    }


def format_restart_alert(rl):
    """(key, message). Names the save, the streak, and what each boot threw away."""
    discarded = rl.get("turnsDiscardedInStreak") or 0
    tail = ""
    r = rl.get("deepestRewind")
    if r:
        tail = (f" Deepest loss on record: a run reached {r['lostFromLabel']} and the next boot "
                f"restarted at {r['resumeLabel']} ({r['turnsDiscarded']} turns thrown away).")
    return ("restart_loop",
            f"RESTART LOOP: {rl['streak']} consecutive boots have resumed the SAME save "
            f"{rl['streakSave']} (now at {rl['lastResumeLabel']}, last boot {rl['lastBootAt']}). "
            f"{len(rl['rewinds'])} rewind boots on record"
            f"{f' (~{discarded} turns discarded in this streak)' if discarded else ''}."
            f"{tail} The harness is not advancing its own starting point - progress made "
            f"after the checkpoint is being discarded at every restart, so the frontier "
            f"cannot move no matter how well the agent plays.")


# ---------------------------------------------------------------- deploy drift
# wq#515 (folded in 06:03Z). "Landed on origin" is not "live". A board full of
# SHIPPED lines can coexist with a game running week-old code - the same class
# of blindness that cost this project five days.
#
# THE TRAP THIS AVOIDS, found while building it (2026-08-13T06:45Z): the board
# reported deployed=62fa545 for 40 minutes and it was wrong. "Deployed" had
# been read off the working tree with `git rev-parse HEAD`. The service runs
# tsx straight out of that tree, so the tree moves under a live process without
# redeploying it: HEAD is what the NEXT restart will load, never proof of what
# is loaded now. The live process had loaded 7a44df9 and the tree had since
# fast-forwarded twice past it. So the deployed sha is resolved from the
# REFLOG AS OF THE PROCESS START TIME, which is the only local record of what
# the tree actually contained when the code was read.
SERVICE_UNIT = os.environ.get("LPP_SERVICE", "lumen-pokemon-live")


def _git(base, *args):
    try:
        r = subprocess.run(["git", "-C", base, *args],
                           capture_output=True, text=True, timeout=15)
        return r.stdout.strip() if r.returncode == 0 else None
    except Exception:
        return None


def _service_start_ms(unit=SERVICE_UNIT):
    """Process start from /proc: locale-free and immune to systemd timestamp formats."""
    try:
        pid = subprocess.run(["systemctl", "show", unit, "-p", "MainPID", "--value"],
                             capture_output=True, text=True, timeout=10).stdout.strip()
        if not pid or pid == "0":
            return None
        with open("/proc/stat") as f:
            btime = next(int(l.split()[1]) for l in f if l.startswith("btime"))
        with open(f"/proc/{pid}/stat") as f:
            field = f.read().rsplit(")", 1)[1].split()      # skip comm, which may contain spaces
        starttime = int(field[19])                          # field 22, 1-based
        hz = os.sysconf("SC_CLK_TCK")
        return (btime + starttime / hz) * 1000
    except Exception:
        return None


def deploy_drift(base=BASE, unit=SERVICE_UNIT, started_ms=None):
    """What is RUNNING vs what is in the tree vs what is on origin.

    started_ms is injectable so the reflog resolution can be proved offline
    against a fixture repo, with no systemd and no live service.
    """
    head = _git(base, "rev-parse", "HEAD")
    if not head:
        return {"ok": False, "reason": f"{base} is not a readable git repo"}
    origin = _git(base, "rev-parse", "origin/main")
    started = started_ms if started_ms is not None else _service_start_ms(unit)

    running, running_src = None, "unknown"
    if started is not None:
        log = _git(base, "reflog", "--date=unix", "--format=%H|%gd") or ""
        for line in log.splitlines():                       # newest first
            sha, _, gd = line.partition("|")
            m = re.search(r"\{(\d+)\}", gd)
            if m and int(m.group(1)) * 1000 <= started:
                running, running_src = sha, "reflog@process-start"
                break
        if running is None and log:
            running, running_src = head, "reflog-exhausted(assumed HEAD)"
    if running is None:
        running, running_src = head, "service-not-running(assumed HEAD)"

    dirty = [l for l in (_git(base, "status", "--porcelain") or "").splitlines()
             if l[3:].startswith(("src/", "tools/"))]
    behind = _git(base, "rev-list", "--count", f"{running}..{head}") if running != head else "0"
    unmerged = _git(base, "rev-list", "--count", f"{head}..{origin}") if origin and origin != head else "0"

    fetch_age_h = None
    try:
        fetch_age_h = (time.time() - os.path.getmtime(f"{base}/.git/FETCH_HEAD")) / 3600.0
    except Exception:
        pass

    st = {
        "ok": True, "running": running, "runningFrom": running_src,
        "head": head, "origin": origin,
        "serviceStartedAt": _iso(started) if started else None,
        "commitsTreeAheadOfRunning": int(behind or 0),
        "commitsOriginAheadOfTree": int(unmerged or 0),
        "dirtyCodePaths": dirty, "originRefAgeHours": fetch_age_h,
    }
    st["drifted"] = bool(st["commitsTreeAheadOfRunning"] or st["commitsOriginAheadOfTree"] or dirty)
    return st


def format_drift_alert(d):
    """(key, message). Every leg is named, because a partial answer here is how
    the 62fa545 misreport happened in the first place."""
    bits = []
    if d["commitsTreeAheadOfRunning"]:
        bits.append(f"the LIVE process is running {d['running'][:7]} while the tree is at "
                    f"{d['head'][:7]} ({d['commitsTreeAheadOfRunning']} commit(s) ahead) - "
                    f"the next restart deploys code nobody has soaked")
    if d["commitsOriginAheadOfTree"]:
        bits.append(f"origin/main {d['origin'][:7]} is {d['commitsOriginAheadOfTree']} commit(s) "
                    f"ahead of the tree - merged work is NOT running")
    if d["dirtyCodePaths"]:
        bits.append(f"{len(d['dirtyCodePaths'])} uncommitted src/tools path(s) in the tree, "
                    f"which a restart would deploy unreviewed: "
                    f"{', '.join(p[3:] for p in d['dirtyCodePaths'][:6])}")
    age = (f" (origin ref last fetched {d['originRefAgeHours']:.1f}h ago)"
           if d.get("originRefAgeHours") is not None else " (origin ref never fetched locally)")
    return ("deploy_drift",
            "DEPLOY DRIFT: " + "; ".join(bits) + "." + age +
            f" Running sha resolved via {d['runningFrom']}, service up since {d['serviceStartedAt']}.")


# ---------------------------------------------------------------- CLI
def one_line(st):
    """Compact line for lpp-stats: the number appears every time anyone measures."""
    if not st.get("ok"):
        return f"FRONTIER: unavailable ({st.get('reason')})"
    tag = "STALLED" if st.get("stalled") else "ok"
    return (f"FRONTIER [{tag}]: badges {st['maxBadges']}, furthest "
            f"{st['furthestLabel']} (path {st['furthestRank']}/{st['lastRank']}), "
            f"next {st.get('nextMilestone') or '(path end)'}, frozen "
            f"{st['frozenHours']:.1f}h since {st['lastAdvanceAt']}")


def restart_line(rl):
    """Compact restart-loop line for lpp-stats."""
    if not rl.get("ok"):
        return f"RESTARTS: unavailable ({rl.get('reason')})"
    tag = "LOOP" if rl.get("looping") else "ok"
    return (f"RESTARTS [{tag}]: {rl['streak']} consecutive boot(s) from {rl.get('streakSave')} "
            f"(now {rl.get('lastResumeLabel')}), {len(rl.get('rewinds', []))} rewind boot(s) on record")


def drift_line(d):
    """Compact deploy-drift line for lpp-stats. Three shas, never one."""
    if not d.get("ok"):
        return f"DEPLOY: unavailable ({d.get('reason')})"
    tag = "DRIFT" if d.get("drifted") else "in-sync"
    return (f"DEPLOY [{tag}]: running {d['running'][:7]}, tree {d['head'][:7]}, "
            f"origin {(d.get('origin') or '???')[:7]}"
            f"{f", +{len(d['dirtyCodePaths'])} uncommitted code path(s)" if d.get('dirtyCodePaths') else ''}")


def main(argv=None):
    import argparse
    ap = argparse.ArgumentParser(description="LPP cross-run forward-progress frontier (read-only)")
    ap.add_argument("--window-hours", type=float, default=DEFAULT_WINDOW_H,
                    help=f"stall window in hours (default {DEFAULT_WINDOW_H})")
    ap.add_argument("--rule", choices=RULES, default="strict")
    ap.add_argument("--json", action="store_true", help="emit the frontier state as JSON")
    ap.add_argument("--one-line", action="store_true", help="single summary line")
    ap.add_argument("--backtest", action="store_true",
                    help="replay all history: advances, gaps, threshold sweep")
    ap.add_argument("--no-live", action="store_true", help="skip the :8871 progress fetch")
    ap.add_argument("--no-persist", action="store_true", help="do not write runtime/frontier.json")
    ap.add_argument("--restart-loop", action="store_true",
                    help="cross-run restart-loop check only (wq#504 MISS 2)")
    ap.add_argument("--drift", action="store_true",
                    help="deployed-vs-tree-vs-origin drift check only")
    ap.add_argument("--min-streak", type=int, default=2,
                    help="consecutive boots on one save before restart_loop alarms")
    ap.add_argument("--base", default=BASE)
    args = ap.parse_args(argv)

    if args.backtest:
        return backtest(args.base)

    if args.restart_loop:
        rl = restart_loop(args.base, min_streak=args.min_streak)
        print(json.dumps(rl, indent=1) if args.json else restart_line(rl))
        if rl.get("looping") and not args.json:
            print("ALERT [{}]: {}".format(*format_restart_alert(rl)))
        return 0

    if args.drift:
        d = deploy_drift(args.base)
        print(json.dumps(d, indent=1) if args.json else drift_line(d))
        if d.get("drifted") and not args.json:
            print("ALERT [{}]: {}".format(*format_drift_alert(d)))
        return 0

    st = compute(args.base, args.window_hours, rule=args.rule, live=not args.no_live)
    if st.get("ok") and not args.no_persist:
        persist(st)
    if args.json:
        print(json.dumps(st, indent=1))
    elif args.one_line:
        print(one_line(st))
    else:
        if not st.get("ok"):
            print(f"frontier: {st.get('reason')}")
            return 1
        print(one_line(st))
        key, msg = format_alert(st)
        if st.get("stalled") or st.get("pathExhausted"):
            print(f"ALERT [{key}]: {msg}")
        else:
            c = st["cost"]
            print(f"  advances recorded: {st['advanceCount']}, maps ever "
                  f"{st['mapsEverCount']}, since last advance: {c['runs']} runs / "
                  f"{c['turns']} turns / {c['tokens']/1e6:.1f}M tokens")
    return 0


if __name__ == "__main__":
    sys.exit(main())
