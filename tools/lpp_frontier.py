#!/usr/bin/env python3
"""lpp_frontier — cross-run FORWARD-PROGRESS frontier for Lumen Plays Pokemon (wq#515).

WHY THIS EXISTS
  From 2026-08-08 to 2026-08-13 the agent ran 34 runs / 4995 turns / 120 wall
  hours and the badge count went 1 -> 1. Every guard reported healthy, because
  every guard was scoped WITHIN a run and keyed on a DECREASE:
    recovery.ts (wq#477)      fires on storyScore < max      -> blind to flatness
    lpp-sentinel check_stall  needs flat score AND a SOFT budget alarm -> never both
    check_loop                needs one map + a 3-tile bbox   -> agent roamed 4 maps
    agent.ts notePotentialOscillation needs <=2 maps in 6 warps, history resets
  This module is the missing shape: WALL-CLOCK, ACROSS runs, keyed on FLATNESS.

WHAT COUNTS AS FORWARD PROGRESS (the load-bearing decision)
  Only two things move the frontier:
    (a) badgeCount rising, and
    (b) reaching a map FURTHER ALONG THE CRITICAL PATH than any map reached before.
  Everything else -- new side maps, a rising raw event-flag count, turns, tokens,
  tool calls -- is CONTEXT, reported in the alert but never resetting the clock.

  This is deliberate and it is backed by the backtest. The obvious guard ("a new
  map counts as advance", suggested in the ticket) is WRONG on this campaign's
  own history: on 2026-08-10 and 2026-08-11, mid-freeze, the agent backtracked
  into Pewter City and entered Museum 2F, Pewter Speech House and Pewter Nidoran
  House for the first time. Those are three never-before-seen map ids during the
  deepest part of the stall. A new-map rule resets the clock on all three and
  breaks one continuous 55.9h freeze into 20.1h + 12.4h + 23.3h fragments.
  Raw event count is the same trap: it ticked 25 (08-10) and 26 (08-12) while
  the game went nowhere, and including it delays first detection by ~27h.
  See --backtest for the numbers.

EVIDENCE (all durable, all outside any single run -- that is the point)
  checkpoints/**/*.json  sidecars: exact ts + map + badges + events. Primary
                         timing source; survives runs by design (wq#490 policy
                         is archive-never-delete).
  events/run-summary-*.json  per-run mapsSeen + badges + startedAt + wallMs.
                         Coarser: an advance inside a run is attributed to the
                         run's END (startedAt + wallMs), the LATEST moment it
                         could have happened, so gaps are never overstated.
  :8871/progress.json    live storyScore / objective. Enrichment only -- there
                         is no durable per-run storyScore on disk (only 6 of 51
                         runs still have an event log), so the frontier cannot
                         depend on it. It is displayed, never used to reset.

READ-ONLY. Reads files and one localhost GET. Never writes to events/,
checkpoints/ or the game; the only file it writes is its own runtime cache.
"""
